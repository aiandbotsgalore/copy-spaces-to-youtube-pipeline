/**
 * Generates the Python script that fetches GitHub Releases and builds podcast.xml, podcast_archive.xml, and clips.xml.
 * Aligned with scripts/generate_rss.py for YouTube 12-hour limit compliance and tri-feed isolation.
 */
export const buildPythonRSSScript = (): string => [
  'import os, json, re, urllib.request, urllib.parse',
  'from pathlib import Path',
  'from datetime import datetime, timezone',
  'from xml.sax.saxutils import escape',
  '',
  'repo = os.environ["REPO"]',
  'token = os.environ.get("GH_TOKEN")',
  'title = os.environ.get("PODCAST_TITLE", "Twitter Spaces Archive")',
  'desc = os.environ.get("PODCAST_DESC", "Twitter Spaces Podcast Archive")',
  'author = os.environ.get("PODCAST_AUTHOR", "Spaces Host")',
  'email = os.environ.get("PODCAST_EMAIL", "spaces@example.com")',
  'image_fallback = os.environ.get("PODCAST_IMAGE", "https://picsum.photos/1400/1400")',
  'owner = repo.split(chr(47))[0]',
  'reponame = repo.split(chr(47))[1] if len(repo.split(chr(47))) > 1 else ""',
  'github_pages_url = f"https://{owner}.github.io/{reponame}/"',
  'rss_url = f"{github_pages_url}podcast.xml"',
  'archive_rss_url = f"{github_pages_url}podcast_archive.xml"',
  'clips_rss_url = f"{github_pages_url}clips.xml"',
  'image = f"{github_pages_url}artwork.jpg" if os.path.exists("artwork.jpg") else (f"{github_pages_url}artwork.png" if os.path.exists("artwork.png") else image_fallback)',
  '',
  'MAX_YOUTUBE_DURATION_SECONDS = (11 * 3600 + 58 * 60)',
  '',
  'def xml_text(v):',
  '    cleaned = re.sub(r"[\\x00-\\x08\\x0b\\x0c\\x0e-\\x1f\\ufffe\\uffff]", "", str(v or ""))',
  '    return escape(cleaned)',
  '',
  'def xml_attr(v):',
  '    cleaned = re.sub(r"[\\x00-\\x08\\x0b\\x0c\\x0e-\\x1f\\ufffe\\uffff]", "", str(v or ""))',
  '    return escape(cleaned, {\'"\': "&quot;", "\'": "&apos;"})',
  '',
  'def parse_duration_seconds(dur_str):',
  '    if not dur_str: return 0',
  '    parts = str(dur_str).strip().split(":")',
  '    try:',
  '        if len(parts) == 3: return int(parts[0]) * 3600 + int(parts[1]) * 60 + int(parts[2])',
  '        elif len(parts) == 2: return int(parts[0]) * 60 + int(parts[1])',
  '    except: pass',
  '    return 0',
  '',
  'releases = []',
  'if os.path.exists("releases.json"):',
  '    try:',
  '        with open("releases.json", "r", encoding="utf-8") as f: releases = json.load(f)',
  '    except: releases = []',
  '',
  'if not releases:',
  '    page = 1',
  '    while True:',
  '        req = urllib.request.Request(f"https://api.github.com/repos/{repo}/releases?per_page=100&page={page}")',
  '        req.add_header("User-Agent", "SpacePipe-RSS")',
  '        if token: req.add_header("Authorization", f"token {token}")',
  '        try:',
  '            with urllib.request.urlopen(req, timeout=20.0) as r: batch = json.loads(r.read().decode())',
  '        except Exception as e:',
  '            print(f"Failed fetching releases page {page}: {e}"); break',
  '        if not batch: break',
  '        releases.extend(batch)',
  '        if len(batch) < 100: break',
  '        page += 1',
  '    if releases:',
  '        try:',
  '            with open("releases.json", "w", encoding="utf-8") as f: json.dump(releases, f, ensure_ascii=False)',
  '        except: pass',
  '',
  'def extract_recorded_datetime(rel):',
  '    body = rel.get("body") or ""',
  '    tag = rel.get("tag_name") or ""',
  '    name = rel.get("name") or ""',
  '    pub = rel.get("published_at") or ""',
  '    m = re.search(r"METADATA::EPISODE_DATE::(\\d{4})[-/]?(\\d{2})[-/]?(\\d{2})", body)',
  '    if m:',
  '        try: return datetime(int(m.group(1)), int(m.group(2)), int(m.group(3)), 12, 0, 0, tzinfo=timezone.utc)',
  '        except: pass',
  '    rec = re.search(r"\\*\\*Recorded:\\*\\*\\s*(\\d{4})[-/]?(\\d{2})[-/]?(\\d{2})", body)',
  '    if rec:',
  '        try: return datetime(int(rec.group(1)), int(rec.group(2)), int(rec.group(3)), 12, 0, 0, tzinfo=timezone.utc)',
  '        except: pass',
  '    for source in [tag, name]:',
  '        tm = re.match(r"^(\\d{4})(\\d{2})(\\d{2})", source)',
  '        if tm:',
  '            try: return datetime(int(tm.group(1)), int(tm.group(2)), int(tm.group(3)), 12, 0, 0, tzinfo=timezone.utc)',
  '            except: pass',
  '    if pub:',
  '        try: return datetime.strptime(pub, \"%Y-%m-%dT%H:%M:%SZ\").replace(tzinfo=timezone.utc)',
  '        except: pass',
  '    return datetime.now(timezone.utc)',
  '',
  'published = [r for r in releases if not r.get("draft") and not r.get("prerelease")]',
  'sorted_releases = sorted(published, key=extract_recorded_datetime, reverse=True)',
  'rss_items = []',
  'archive_items = []',
  'for release in sorted_releases:',
  '    dt = extract_recorded_datetime(release)',
  '    rfc822 = dt.strftime("%a, %d %b %Y %H:%M:%S +0000")',
  '    body = release.get("body") or ""',
  '    m = re.search(r"METADATA::DURATION::(\\S+)", body)',
  '    duration = m.group(1) if m else "00:00:00"',
  '    dur_seconds = parse_duration_seconds(duration)',
  '    yt_match = re.search(r"METADATA::YOUTUBE_STATUS::(\\S+)", body)',
  '    yt_status = yt_match.group(1).upper() if yt_match else "APPROVED"',
  '    is_yt_approved = yt_status not in ["UNLISTED", "REJECTED", "EXCLUDED"]',
  '    mp3_assets = [',
  '        a for a in release.get("assets", [])',
  '        if a.get("name", "").endswith(".mp3")',
  '        and not a.get("name", "").endswith("_clips.json")',
  '        and not a.get("name", "").endswith("_short.mp4")',
  '        and not a.get("name", "").startswith("clip_")',
  '        and not re.match(r"^(?:(\\d+)h)?(\\d+)m(\\d+)s_", a.get("name", ""))',
  '    ]',
  '    if not mp3_assets: continue',
  '    mp3_assets.sort(key=lambda a: a.get("name", ""))',
  '    is_multi = len(mp3_assets) > 1',
  '    for part_idx, asset in enumerate(mp3_assets, start=1):',
  '        m_part = re.search(r"[-_]Part(\\d+)\\.mp3$", asset.get("name", ""), re.IGNORECASE)',
  '        part_num = int(m_part.group(1)) if m_part else part_idx',
  '        item_title = f"{release.get(\'name\', \'Untitled Space\')} (Part {part_num})" if is_multi else release.get("name", "Untitled Space")',
  '        item_guid = f"{release.get(\'id\')}_part{part_num}" if is_multi else str(release.get("id"))',
  '        if is_multi and dur_seconds > 0:',
  '            CHUNK_SECS = 36000',
  '            part_start = (part_num - 1) * CHUNK_SECS',
  '            part_dur_sec = max(0, min(CHUNK_SECS, dur_seconds - part_start))',
  '            part_dur_str = f"{part_dur_sec // 3600:02d}:{(part_dur_sec % 3600) // 60:02d}:{part_dur_sec % 60:02d}"',
  '        else:',
  '            part_dur_str = duration',
  '        full_desc = xml_text(body[:800])',
  '        item_desc = full_desc.replace(f"Duration: {duration}", f"Duration: {part_dur_str} (Total: {duration})") if is_multi else full_desc',
  '        url = asset.get("browser_download_url", "")',
  '        size = asset.get("size", 0)',
  '        t = xml_text(item_title)',
  '        item_xml = (',
  '            "  <item>\\n"',
  '            f"    <title>{t}</title>\\n"',
  '            f"    <description>{item_desc}</description>\\n"',
  '            f"    <pubDate>{rfc822}</pubDate>\\n"',
  '            f\'    <enclosure url="{xml_attr(url)}" length="{size}" type="audio/mpeg"/>\\n\'',
  '            f\'    <guid isPermaLink="false">{xml_text(item_guid)}</guid>\\n\'',
  '            f"    <itunes:author>{xml_text(author)}</itunes:author>\\n"',
  '            f"    <itunes:duration>{xml_text(part_dur_str)}</itunes:duration>\\n"',
  '            "    <itunes:explicit>no</itunes:explicit>\\n"',
  '            "  </item>"',
  '        )',
  '        archive_items.append(item_xml)',
  '        # YouTube 11h 58m limit and approved check',
  '        part_seconds = parse_duration_seconds(part_dur_str)',
  '        if is_yt_approved and part_seconds <= MAX_YOUTUBE_DURATION_SECONDS:',
  '            rss_items.append(item_xml)',
  '',
  'lbd = datetime.now(timezone.utc).strftime("%a, %d %b %Y %H:%M:%S +0000")',
  'def build_feed(feed_title, feed_desc, feed_url, items):',
  '    ci = "\\n".join(items)',
  '    return (',
  '        \'<?xml version="1.0" encoding="UTF-8"?>\\n\'',
  '        \'<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd" xmlns:atom="http://www.w3.org/2005/Atom">\\n\'',
  '        \'  <channel>\\n\'',
  '        f\'    <title>{xml_text(feed_title)}</title>\\n\'',
  '        f\'    <link>{xml_attr(github_pages_url)}</link>\\n\'',
  '        f\'    <description>{xml_text(feed_desc)}</description>\\n\'',
  '        \'    <language>en-us</language>\\n\'',
  '        f\'    <lastBuildDate>{lbd}</lastBuildDate>\\n\'',
  '        f\'    <atom:link href="{xml_attr(feed_url)}" rel="self" type="application/rss+xml"/>\\n\'',
  '        f\'    <itunes:author>{xml_text(author)}</itunes:author>\\n\'',
  '        f\'    <itunes:owner><itunes:name>{xml_text(author)}</itunes:name><itunes:email>{xml_text(email)}</itunes:email></itunes:owner>\\n\'',
  '        f\'    <itunes:image href="{xml_attr(image)}"/>\\n\'',
  '        f\'    <image><url>{xml_attr(image)}</url><title>{xml_text(feed_title)}</title><link>{xml_attr(github_pages_url)}</link></image>\\n\'',
  '        \'    <itunes:category text="Technology"/>\\n\'',
  '        \'    <itunes:explicit>no</itunes:explicit>\\n\'',
  '        f\'{ci}\\n\'',
  '        \'  </channel>\\n\'',
  '        \'</rss>\'',
  '    )',
  '',
  'rss = build_feed(title, desc, rss_url, rss_items)',
  'archive_rss = build_feed(f"{title} (Archive)", f"{desc} (Complete unconstrained archive)", archive_rss_url, archive_items)',
  'with open("podcast.xml", "w", encoding="utf-8") as f: f.write(rss)',
  'with open("podcast_archive.xml", "w", encoding="utf-8") as f: f.write(archive_rss)',
  'print("Successfully generated podcast.xml and podcast_archive.xml")',
  '',
  '# Generate clips.xml if clips catalog exists',
  'clips_cat = Path("public/clips/clips_catalog.json") if Path("public/clips/clips_catalog.json").exists() else Path("best_saved_clips/clips_catalog.json")',
  'if clips_cat.exists():',
  '    try:',
  '        with open(clips_cat, "r", encoding="utf-8") as cf: raw_clips = json.load(cf)',
  '        clip_items = []',
  '        for c in raw_clips:',
  '            c_url = c.get("download_url") or c.get("file_path")',
  '            if not c_url or not str(c_url).startswith("http"): continue',
  '            c_title = xml_text(f"[{c.get(\'category\', \'Highlights\')}] {c.get(\'title\', \'Highlight Moment\')}")',
  '            c_dur = float(c.get("duration", 60.0))',
  '            c_dur_str = f"{int(c_dur // 60):02d}:{int(c_dur % 60):02d}"',
  '            c_desc = xml_text(c.get("reason", "") or c.get("transcript_snippet", "") or c.get("title", ""))',
  '            c_guid = f"clip_{abs(hash(c_url + c.get(\'title\', \'\')))}"',
  '            c_xml = (',
  '                "  <item>\\n"',
  '                f"    <title>{c_title}</title>\\n"',
  '                f"    <description>{c_desc}</description>\\n"',
  '                f"    <pubDate>{lbd}</pubDate>\\n"',
  '                f\'    <enclosure url="{xml_attr(c_url)}" length="{int(c_dur * 16000)}" type="audio/mpeg"/>\\n\'',
  '                f\'    <guid isPermaLink="false">{xml_text(c_guid)}</guid>\\n\'',
  '                f"    <itunes:author>{xml_text(author)}</itunes:author>\\n"',
  '                f"    <itunes:duration>{xml_text(c_dur_str)}</itunes:duration>\\n"',
  '                "    <itunes:explicit>yes</itunes:explicit>\\n"',
  '                "  </item>"',
  '            )',
  '            clip_items.append(c_xml)',
  '        if clip_items:',
  '            clips_rss = build_feed(f"{title} Best Clips", f"Curated highlight clips from {title}", clips_rss_url, clip_items)',
  '            with open("clips.xml", "w", encoding="utf-8") as f: f.write(clips_rss)',
  '            print(f"Successfully generated clips.xml ({len(clip_items)} clips)")',
  '    except Exception as ce:',
  '        print(f"Warning generating clips.xml: {ce}")',
].join('\n');
