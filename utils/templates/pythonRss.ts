/**
 * Generates the Python script that fetches GitHub Releases and builds podcast.xml
 */
export const buildPythonRSSScript = (): string => [
  'import os, json, re, urllib.request',
  'from datetime import datetime',
  'from xml.sax.saxutils import escape',
  '',
  'repo = os.environ["REPO"]',
  'token = os.environ["GH_TOKEN"]',
  'title = os.environ.get("PODCAST_TITLE", "Twitter Spaces Archive")',
  'desc = os.environ.get("PODCAST_DESC", "Twitter Spaces Podcast Archive")',
  'author = os.environ.get("PODCAST_AUTHOR", "Spaces Host")',
  'email = os.environ.get("PODCAST_EMAIL", "spaces@example.com")',
  'image_fallback = os.environ.get("PODCAST_IMAGE", "https://picsum.photos/1400/1400")',
  'github_pages_url = f"https://{repo.split(chr(47))[0]}.github.io/{repo.split(chr(47))[1]}/"',
  'rss_url = f"{github_pages_url}podcast.xml"',
  'image = f"{github_pages_url}artwork.jpg" if os.path.exists("artwork.jpg") else image_fallback',
  '',
  'def xml_text(v):',
  '    return escape(str(v or ""))',
  '',
  'def xml_attr(v):',
  '    return escape(str(v or ""), {\'"\': "&quot;"})',
  '',
  'releases = []',
  'page = 1',
  'while True:',
  '    req = urllib.request.Request(',
  '        f"https://api.github.com/repos/{repo}/releases?per_page=100&page={page}"',
  '    )',
  '    req.add_header("Authorization", f"token {token}")',
  '    req.add_header("Accept", "application/vnd.github.v3+json")',
  '    try:',
  '        with urllib.request.urlopen(req) as r: batch = json.loads(r.read())',
  '    except Exception as e:',
  '        print(f"Failed fetching releases page {page}: {e}"); exit(1)',
  '    if not batch: break',
  '    releases.extend(batch)',
  '    if len(batch) < 100: break',
  '    page += 1',
  '',
  'def extract_recorded_datetime(rel):',
  '    body = rel.get("body") or ""',
  '    tag = rel.get("tag_name") or ""',
  '    name = rel.get("name") or ""',
  '    pub = rel.get("published_at") or ""',
  '    m = re.search(r"METADATA::EPISODE_DATE::(\\d{4})[-/]?(\\d{2})[-/]?(\\d{2})", body)',
  '    if m:',
  '        try: return datetime(int(m.group(1)), int(m.group(2)), int(m.group(3)), 12, 0, 0)',
  '        except: pass',
  '    rec = re.search(r"\\*\\*Recorded:\\*\\*\\s*(\\d{4})[-/]?(\\d{2})[-/]?(\\d{2})", body)',
  '    if rec:',
  '        try: return datetime(int(rec.group(1)), int(rec.group(2)), int(rec.group(3)), 12, 0, 0)',
  '        except: pass',
  '    t = re.search(r"^(?:v)?(\\d{4})[-_]?(\\d{2})[-_]?(\\d{2})", tag)',
  '    if t:',
  '        try: return datetime(int(t.group(1)), int(t.group(2)), int(t.group(3)), 12, 0, 0)',
  '        except: pass',
  '    n = re.search(r"\\b(\\d{4})[-/](\\d{2})[-/](\\d{2})\\b", name)',
  '    if n:',
  '        try: return datetime(int(n.group(1)), int(n.group(2)), int(n.group(3)), 12, 0, 0)',
  '        except: pass',
  '    if pub:',
  '        try: return datetime.strptime(pub, "%Y-%m-%dT%H:%M:%SZ")',
  '        except: pass',
  '    return datetime.now()',
  '',
  'published = [r for r in releases if not r.get("draft") and not r.get("prerelease")]',
  'sorted_releases = sorted(published, key=extract_recorded_datetime, reverse=True)',
  'rss_items = []',
  'for release in sorted_releases:',
  '    dt = extract_recorded_datetime(release)',
  '    rfc822 = dt.strftime("%a, %d %b %Y %H:%M:%S GMT")',
  '    body = release.get("body") or ""',
  '    m = re.search(r"METADATA::DURATION::(\\d+:?\\d{2}:\\d{2})", body)',
  '    duration = m.group(1) if m else "00:00:00"',
  '    dur_seconds = sum(int(x) * 60**i for i, x in enumerate(reversed(duration.split(":")))) if duration else 0',
  '    if dur_seconds > (11 * 3600 + 58 * 60): continue',
  '    mp3_assets = [a for a in release.get("assets", []) if a.get("name", "").endswith(".mp3")]',
  '    if not mp3_assets: continue',
  '    non_clip_mp3s = [a for a in mp3_assets if not re.match(r"^\\d+(?:h\\d+)?m\\d+s_", a.get("name", "")) ]',
  '    asset = max(non_clip_mp3s if non_clip_mp3s else mp3_assets, key=lambda a: a.get("size", 0))',
  '    url = asset["browser_download_url"]',
  '    size = asset["size"]',
  '    guid = str(asset["id"])',
  '    t = xml_text(release.get("name") or "Untitled Space")',
  '    rss_items.append(',
  '        "  <item>\\n"',
  '        f"    <title>{t}</title>\\n"',
  '        f"    <description>{t} - Space Replay</description>\\n"',
  '        f"    <pubDate>{rfc822}</pubDate>\\n"',
  '        f\'    <enclosure url="{xml_attr(url)}" length="{size}" type="audio/mpeg"/>\\n\'',
  '        f\'    <guid isPermaLink="false">{xml_text(guid)}</guid>\\n\'',
  '        f"    <itunes:duration>{xml_text(duration)}</itunes:duration>\\n"',
  '        "    <itunes:explicit>no</itunes:explicit>\\n"',
  '        "  </item>"',
  '    )',
  '',
  'lbd = datetime.now().strftime("%a, %d %b %Y %H:%M:%S GMT")',
  'channel_items = "\\n".join(rss_items)',
  'rss = (',
  '    \'<?xml version="1.0" encoding="UTF-8"?>\\n\'',
  '    \'<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd" xmlns:atom="http://www.w3.org/2005/Atom">\\n\'',
  '    \'  <channel>\\n\'',
  '    f\'    <title>{xml_text(title)}</title>\\n\'',
  '    f\'    <link>{xml_attr(github_pages_url)}</link>\\n\'',
  '    f\'    <description>{xml_text(desc)}</description>\\n\'',
  '    \'    <language>en-us</language>\\n\'',
  '    f\'    <lastBuildDate>{lbd}</lastBuildDate>\\n\'',
  '    f\'    <atom:link href="{xml_attr(rss_url)}" rel="self" type="application/rss+xml"/>\\n\'',
  '    f\'    <itunes:author>{xml_text(author)}</itunes:author>\\n\'',
  '    f\'    <itunes:owner><itunes:name>{xml_text(author)}</itunes:name><itunes:email>{xml_text(email)}</itunes:email></itunes:owner>\\n\'',
  '    f\'    <itunes:image href="{xml_attr(image)}"/>\\n\'',
  '    f\'    <image><url>{xml_attr(image)}</url><title>{xml_text(title)}</title><link>{xml_attr(github_pages_url)}</link></image>\\n\'',
  '    \'    <itunes:category text="Technology"/>\\n\'',
  '    \'    <itunes:explicit>no</itunes:explicit>\\n\'',
  '    f\'{channel_items}\\n\'',
  '    \'  </channel>\\n\'',
  '    \'</rss>\'',
  ')',
  'with open("podcast.xml", "w", encoding="utf-8") as f: f.write(rss)',
  'print("Successfully generated podcast.xml")',
].join('\n');
